#!/usr/bin/env node
'use strict';
// Build an offline, attributed supplement. Do not label outside sources as
// original exam practice or fabricate grammatical analysis for them.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const ctx=vm.createContext({console,URL,localStorage:{getItem:()=>null},document:{getElementById:()=>({})}});
for(const name of ['js/config','data/vocabulary','data/collocations','data/learning','data/builtin-study','data/exam-notebook','data/vocabulary-enrichment','data/authored-scenarios','js/exam-notes','js/state','js/builtin','js/examples'])
  vm.runInContext(fs.readFileSync(path.join(root,'assets',name+'.js'),'utf8'),ctx);
const run=s=>vm.runInContext(s,ctx),difficulty=require('./scenario_difficulty.cjs').createDifficultyResolver(ctx);
const input=JSON.parse(fs.readFileSync(path.join(root,'research/tatoeba-sentence-pairs.json'),'utf8'));
const entries=JSON.parse(run(`JSON.stringify(VOCABULARY.map(entry=>({word:entry.word,partOfSpeech:entry.partOfSpeech,forms:[...new Set(builtinTargetAliases(entry.word).flatMap(alias=>[...wordForms(alias.toLowerCase()),...(BUILTIN_IRREGULAR_FORMS[alias.toLowerCase()]||[])]))],existing:(getExamNotebook(entry)?.examples||[]).map(row=>row.text),archived:(getOriginalStudy(entry)?.examples||[]).map(row=>row.text)})))`));
const normalize=s=>s.replace(/\s+/g,' ').trim().toLowerCase(),esc=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const sentenceMap=new Map();
for(const row of input.sentences){
  if(!row.text||!row.translationZh||!row.translationOriginal||!/^\d+$/.test(row.enId)||!/^\d+$/.test(row.zhId)||!row.enAuthor||!row.zhAuthor)throw Error('Incomplete Tatoeba attribution');
  const key=normalize(row.text),id=`t${row.enId}_${row.zhId}`;
  if(sentenceMap.has(key))throw Error('Duplicate English reference sentence');
  sentenceMap.set(key,{...row,id,source:'tatoeba'});
}
const pool=[...sentenceMap.values()],byWord={},remaining=[];
const LIMIT=12,TARGET=11;
for(const entry of entries){
  if(!entry.forms.length)continue;
  const expression=new RegExp('(^|[^\\p{L}\\p{N}_])('+entry.forms.map(esc).sort((a,b)=>b.length-a.length).join('|')+')(?=$|[^\\p{L}\\p{N}_])','iu');
  const already=new Set([...entry.existing,...entry.archived].map(normalize));
  const candidates=[];
  for(const row of pool){
    if(already.has(normalize(row.text))||!expression.test(row.text))continue;
    if(entry.word==='am/a.m.'&&!/\ba\.m\./i.test(row.text))continue;
    if(entry.word==='pm/p.m.'&&!/\bp\.m\./i.test(row.text))continue;
    if(entry.word==='March'&&!/\bMarch\b/.test(row.text))continue;
    if(entry.word==='march'&&!/\bmarch(?:es|ed|ing)?\b/.test(row.text))continue;
    if(entry.word==='August'&&!/\bAugust\b/.test(row.text))continue;
    if(entry.word==='May'&&!/\bMay\b/.test(row.text))continue;
    if(!ctx.builtinClozeQuestion(entry,row)||!ctx.likelyCompleteSentence(row.text,ctx.sentenceWords(row.text)))continue;
    const assessment=difficulty.analyze(row.text,entry.word);
    if(assessment.high.length)continue;
    const n=ctx.sentenceWords(row.text).length;
    const cue=/\b(?:because|although|despite|but|whereas|however|so that|therefore|since|when|while|before|after|if|unless|which|who)\b/i.test(row.text);
    candidates.push({row,score:(n>=15?20:n>=12?12:6)+(cue?6:0)-assessment.unknown.length});
  }
  candidates.sort((a,b)=>b.score-a.score||a.row.enId.localeCompare(b.row.enId,'en',{numeric:true}));
  const ids=candidates.slice(0,LIMIT).map(item=>item.row.id);
  if(ids.length)byWord[entry.word]=ids;
  const total=entry.existing.length+ids.length;
  if(total<TARGET)remaining.push({word:entry.word,authored:entry.existing.length,references:ids.length,missingContexts:TARGET-total});
}
const used=new Set(Object.values(byWord).flat()),sentences=Object.fromEntries(pool.filter(row=>used.has(row.id)).map(row=>[row.id,row]));
const stats={sourcePairs:pool.length,uniqueReferenceSentences:used.size,referenceAppearances:Object.values(byWord).reduce((sum,ids)=>sum+ids.length,0),wordsWithReferences:Object.keys(byWord).length,totalWords:entries.length,targetContextsPerWord:TARGET,completedWords:entries.length-remaining.length,remainingWords:remaining.length,missingContexts:remaining.reduce((sum,row)=>sum+row.missingContexts,0)};
const data={description:'Offline reference examples from Tatoeba. English and Chinese authors and sentence IDs are retained; Chinese script may be adapted automatically. Reference examples are separate from self-authored examination-style contexts.',stats,sentences,byWord};
for(const [name,content] of Object.entries({
 'assets/data/reference-sentences.js':'"use strict";\n// Generated by research/build_reference_sentences.cjs.\nconst GSAT_REFERENCE_SENTENCES = '+JSON.stringify(data)+';\n',
 'research/reference_sentence_coverage.json':JSON.stringify({stats,remaining},null,2)+'\n',
})){
 const file=path.join(root,name);
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error(`Stale generated file: ${name}`);}
 else fs.writeFileSync(file,content);
}
console.log(JSON.stringify(stats));
